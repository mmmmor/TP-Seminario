export function useTweaks(defaults) {
  const [values, setValues] = useState(defaults);
  const setTweak = useCallback((keyOrEdits, val) => {
    const edits = typeof keyOrEdits === 'object' && keyOrEdits !== null
      ? keyOrEdits : { [keyOrEdits]: val };
    setValues((prev) => ({ ...prev, ...edits }));
  }, []);
  return [values, setTweak];
}

export function TweaksPanel({ title = 'Tweaks', children }) {
  const [open, setOpen] = useState(true);
  const panelRef = useRef(null);
  const dragRef = useRef({ dragging: false, ox: 0, oy: 0 });

  useEffect(() => {
    const style = document.createElement('style');
    style.textContent = STYLE;
    document.head.appendChild(style);
    return () => document.head.removeChild(style);
  }, []);

  const onMouseDown = (e) => {
    dragRef.current = { dragging: true, ox: e.clientX - panelRef.current.offsetLeft, oy: e.clientY - panelRef.current.offsetTop };
    window.addEventListener('mousemove', onMouseMove);
    window.addEventListener('mouseup', onMouseUp);
  };
  const onMouseMove = (e) => {
    if (!dragRef.current.dragging || !panelRef.current) return;
    panelRef.current.style.right = 'auto';
    panelRef.current.style.bottom = 'auto';
    panelRef.current.style.left = `${e.clientX - dragRef.current.ox}px`;
    panelRef.current.style.top = `${e.clientY - dragRef.current.oy}px`;
  };
  const onMouseUp = () => {
    dragRef.current.dragging = false;
    window.removeEventListener('mousemove', onMouseMove);
    window.removeEventListener('mouseup', onMouseUp);
  };

  return (
    <div ref={panelRef} className="twk-panel">
      <div className="twk-hd" onMouseDown={onMouseDown}>
        <b>{title}</b>
        <button className="twk-x" onClick={() => setOpen((o) => !o)} aria-label={open ? 'Colapsar' : 'Expandir'}>
          {open ? '−' : '+'}
        </button>
      </div>
      {open && <div className="twk-body">{children}</div>}
    </div>
  );
}

export function TweakSection({ label }) {
  return <div className="twk-sect">{label}</div>;
}

export function TweakRow({ label, value, children }) {
  return (
    <div className="twk-row">
      {label && (
        <div className="twk-lbl">
          <span>{label}</span>
          {value !== undefined && <span className="twk-val">{value}</span>}
        </div>
      )}
      {children}
    </div>
  );
}

export function TweakToggle({ label, value, onChange }) {
  return (
    <div className="twk-row twk-row-h">
      <div className="twk-lbl"><span>{label}</span></div>
      <button type="button" className="twk-toggle" data-on={value ? '1' : '0'}
              onClick={() => onChange(!value)} aria-pressed={value}>
        <i />
      </button>
    </div>
  );
}

export function TweakText({ label, value, placeholder, onChange }) {
  return (
    <TweakRow label={label}>
      <input className="twk-field" type="text" value={value} placeholder={placeholder}
             onChange={(e) => onChange(e.target.value)} />
    </TweakRow>
  );
}

function __twkIsLight(hex) {
  const h = String(hex).replace('#', '');
  const x = h.length === 3 ? h.replace(/./g, (c) => c + c) : h.padEnd(6, '0');
  const n = parseInt(x.slice(0, 6), 16);
  if (Number.isNaN(n)) return true;
  const r = (n >> 16) & 255, g = (n >> 8) & 255, b = n & 255;
  return r * 299 + g * 587 + b * 114 > 148000;
}

const TwkCheck = ({ light }) => (
  <svg viewBox="0 0 14 14" aria-hidden="true">
    <path d="M3 7.2 5.8 10 11 4.2" fill="none" strokeWidth="2.2"
          strokeLinecap="round" strokeLinejoin="round"
          stroke={light ? 'rgba(0,0,0,.78)' : '#fff'} />
  </svg>
);

export function TweakColor({ label, value, options, onChange }) {
  if (!options || !options.length) {
    return (
      <div className="twk-row twk-row-h">
        <div className="twk-lbl"><span>{label}</span></div>
        <input type="color" className="twk-swatch" value={value}
               onChange={(e) => onChange(e.target.value)} />
      </div>
    );
  }
  const key = (o) => String(JSON.stringify(o)).toLowerCase();
  const cur = key(value);
  return (
    <TweakRow label={label}>
      <div className="twk-chips" role="radiogroup">
        {options.map((o, i) => {
          const colors = Array.isArray(o) ? o : [o];
          const [hero, ...rest] = colors;
          const sup = rest.slice(0, 4);
          const on = key(o) === cur;
          return (
            <button key={i} type="button" className="twk-chip" role="radio"
                    aria-checked={on} data-on={on ? '1' : '0'}
                    style={{ background: hero }}
                    onClick={() => onChange(o)}>
              {sup.length > 0 && <span>{sup.map((c, j) => <i key={j} style={{ background: c }} />)}</span>}
              {on && <TwkCheck light={__twkIsLight(hero)} />}
            </button>
          );
        })}
      </div>
    </TweakRow>
  );
}
